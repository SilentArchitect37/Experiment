    def verify_improvement(
        self,
        old_generator_class,
        new_generator_code: str,
        test_suite: List[CodeSpec]
    ) -> ImprovementProof:
        """
        Prove that new version is better than old version.

        Verification criteria:
        1. All tests that passed before still pass (no regressions)
        2. Accuracy improved by at least 10%
        3. Speed maintained or improved
        4. No new bugs introduced
        """

        print("\n" + "="*70)
        print("IMPROVEMENT VERIFICATION")
        print("="*70)

        # Benchmark old version
        print("\nBenchmarking OLD version...")
        old_results = self._benchmark_generator(
            old_generator_class,
            test_suite,
            "Old"
        )

        # Execute new code to get class
        print("\nBenchmarking NEW version...")
        try:
            namespace = {}
            exec(new_generator_code, namespace)
            new_generator_class = namespace['ImprovedCodeGenerator']

            new_results = self._benchmark_generator(
                new_generator_class,
                test_suite,
                "New"
            )
        except Exception as e:
            print(f"✗ New version failed to execute: {e}")
            return ImprovementProof(
                verified=False,
                old_accuracy=old_results['accuracy'],
                new_accuracy=0.0,
                improvement=0.0,
                all_tests_pass=False,
                no_regressions=False,
                speed_maintained=False,
                confidence=0.0,
                reasoning=f"New code execution failed: {e}"
            )

        # Compare results
        print("\n" + "-"*70)
        print("COMPARISON")
        print("-"*70)

