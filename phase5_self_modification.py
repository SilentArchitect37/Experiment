        new_acc = new_results['accuracy']
        improvement = new_acc - old_acc

        print(f"Old accuracy: {old_acc:.1%}")
        print(f"New accuracy: {new_acc:.1%}")
        print(f"Improvement: {improvement:+.1%}")

        # Check criteria
        all_tests_pass = new_results['passed'] >= old_results['passed']
        no_regressions = new_results['passed'] >= old_results['passed']
        speed_maintained = True  # Simplified for demo

        improved = new_acc > old_acc
        significant = improvement >= 0.1  # At least 10% improvement

